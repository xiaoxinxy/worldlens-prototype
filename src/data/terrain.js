export function terrainTypeFor(code) {
  return terrainTypes.find((type) => type.code === code) || null
}

export function getTerrainFeature(id) {
  return terrainFeatures.find((feature) => feature.id === id || feature.name_en === id || feature.name === id) || null
}

export function filterTerrainFeatures(features = terrainFeatures, filters = {}) {
  const type = String(filters.type || '').trim()
  const continent = String(filters.continent || '').trim()
  const country = String(filters.country || '').trim().toUpperCase()
  const tag = String(filters.tag || '').trim().toLowerCase()
  const keyword = String(filters.keyword || filters.q || '').trim().toLowerCase()

  return features.filter((feature) => {
    if (type && feature.type !== type) return false
    if (continent && feature.continent !== continent) return false
    if (country && !feature.country_codes.includes(country)) return false
    if (tag && !feature.tags.some((item) => item.toLowerCase().includes(tag))) return false
    if (!keyword) return true
    const haystack = [
      feature.name,
      feature.name_en,
      feature.type_label,
      feature.continent,
      feature.region,
      feature.summary,
      feature.formation_reason,
      feature.climate_impact,
      feature.civilization_impact,
      feature.ecology,
      feature.human_activity,
      feature.highest_point,
      feature.relief_signature,
      feature.tectonics?.title,
      ...(feature.search_aliases || []),
      ...feature.tags,
      ...feature.country_codes
    ].join(' ').toLowerCase()
    return haystack.includes(keyword)
  })
}

export function featuredTerrainFeatures(limit = 6) {
  const priority = [
    'himalayas',
    'tibetan-plateau',
    'sahara-desert',
    'amazon-river',
    'east-african-rift',
    'mariana-trench',
    'rocky-mountains',
    'mid-atlantic-ridge'
  ]
  return priority
    .map((id) => getTerrainFeature(id))
    .filter(Boolean)
    .slice(0, limit)
}

export function relatedTerrainFeatures(id) {
  const feature = getTerrainFeature(id)
  if (!feature) return []
  const direct = feature.related_terrain_ids
    .map((terrainId) => getTerrainFeature(terrainId))
    .filter(Boolean)
  const similar = terrainFeatures.filter((item) =>
    item.id !== feature.id &&
    item.type === feature.type &&
    !direct.some((related) => related.id === item.id)
  )
  return [...direct, ...similar].slice(0, 6)
}

export function terrainForCountry(code) {
  const countryCode = String(code || '').toUpperCase()
  return terrainFeatures.filter((feature) => feature.country_codes.includes(countryCode))
}
