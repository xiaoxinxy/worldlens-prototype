function makeFeature(feature) {
  const shape = feature.shape || terrainShapeCatalog[feature.id] || defaultTerrainShape(feature)
  const coverImage = feature.cover_image || ''
  return {
    created_at: now,
    updated_at: now,
    related_routes: [],
    related_terrain_ids: [],
    shape,
    tectonics: feature.tectonics || terrainTectonicsCatalog[feature.id] || null,
    relief_signature: feature.relief_signature || terrainReliefByType[feature.type] || 'surface-form',
    highest_point: feature.highest_point || terrainPeakCatalog[feature.id] || feature.elevation || '',
    search_aliases: [],
    ...feature,
    cover_image: coverImage,
    gallery_images: [coverImage, ...(feature.gallery_images || [])].filter(Boolean)
  }
}

function defaultTerrainShape(feature) {
  const linearTypes = new Set(['mountain', 'river', 'rift', 'trench', 'reef', 'ridge', 'island_chain'])
  if (linearTypes.has(feature.type)) {
    return {
      kind: 'line',
      path: [
        [feature.latitude - 2, feature.longitude - 4],
        [feature.latitude, feature.longitude],
        [feature.latitude + 2, feature.longitude + 4]
      ],
      width: 0.018
    }
  }
  return {
    kind: 'area',
    center: [feature.latitude, feature.longitude],
    radius: feature.type === 'volcano' ? 0.1 : 0.24,
    aspect: [1, 1]
  }
}

