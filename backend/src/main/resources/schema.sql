create table if not exists wl_user (
  id bigint generated by default as identity primary key,
  username varchar(64) not null unique,
  password_hash varchar(120) not null,
  nickname varchar(80) not null,
  avatar_url text,
  is_admin boolean not null default false,
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp
);

create table if not exists wl_auth_token (
  token varchar(96) primary key,
  user_id bigint not null,
  expires_at timestamp not null,
  created_at timestamp not null default current_timestamp,
  constraint fk_auth_token_user foreign key (user_id) references wl_user(id) on delete cascade
);

create table if not exists wl_favorite (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  item_id varchar(120) not null,
  item_type varchar(64) not null,
  title varchar(160) not null,
  cover_image varchar(500),
  payload clob,
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp,
  constraint fk_favorite_user foreign key (user_id) references wl_user(id) on delete cascade,
  constraint uk_favorite_user_item unique (user_id, item_id)
);

alter table wl_favorite add column if not exists payload clob;

alter table wl_user alter column avatar_url character large object;
alter table wl_user add column if not exists is_admin boolean not null default false;

create table if not exists wl_history (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  item_id varchar(120) not null,
  item_type varchar(64) not null,
  title varchar(160) not null,
  slug varchar(160),
  cover_image varchar(500),
  visited_count int not null default 1,
  last_visited_at timestamp not null default current_timestamp,
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp,
  constraint fk_history_user foreign key (user_id) references wl_user(id) on delete cascade,
  constraint uk_history_user_item unique (user_id, item_id)
);

create table if not exists wl_ocean_current (
  id varchar(120) primary key,
  name varchar(160) not null,
  name_en varchar(160) not null,
  kind varchar(32) not null,
  basin varchar(120) not null,
  current_system varchar(180) not null,
  direction text,
  source text,
  effect text,
  impact_tags_json text,
  textbook_note text,
  influence_lat double,
  influence_lng double,
  influence_radius double,
  influence_role varchar(80),
  path_json text,
  enabled boolean not null default true,
  sort_order int not null default 0,
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp
);

alter table wl_ocean_current add column if not exists enabled boolean not null default true;

create table if not exists wl_terrain_feature (
  id varchar(120) primary key,
  name varchar(160) not null,
  name_en varchar(160),
  terrain_type varchar(80) not null,
  type_label varchar(100) not null,
  continent varchar(80),
  region varchar(120),
  country_codes_json text,
  latitude double not null,
  longitude double not null,
  summary text,
  formation_reason text,
  highest_point varchar(160),
  length_label varchar(160),
  area_label varchar(160),
  tags_json text,
  cover_image varchar(500),
  enabled boolean not null default true,
  sort_order int not null default 100,
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp
);

create table if not exists wl_country_profile (
  code varchar(3) primary key,
  name varchar(120) not null,
  name_en varchar(160) not null,
  continent varchar(80) not null,
  region varchar(120),
  capital varchar(120),
  latitude double not null,
  longitude double not null,
  population bigint not null default 0,
  area_km2 double not null default 0,
  languages_json text,
  language_group varchar(80) not null,
  language_group_label varchar(120) not null,
  language_color varchar(20) not null,
  tone_group varchar(40) not null,
  tone_group_label varchar(80) not null,
  tone_color varchar(20) not null,
  summary text,
  culture_note text,
  civilization_tags_json text,
  cover_image varchar(500),
  enabled boolean not null default true,
  sort_order int not null default 100,
  created_at timestamp not null default current_timestamp,
  updated_at timestamp not null default current_timestamp
);

create index if not exists idx_country_profile_continent on wl_country_profile(continent);
create index if not exists idx_country_profile_enabled_sort on wl_country_profile(enabled, sort_order);

create table if not exists wl_content_entry (
  id bigint generated by default as identity primary key,
  content_module varchar(80) not null,
  entry_id varchar(120) not null,
  title varchar(180) not null,
  subtitle varchar(220),
